#!/usr/bin/env python3
"""Maintain a vault's wiki/glossary.md and the links to it.

    python3 glossary.py --vault . build            # regenerate the ID entries from the registers
    python3 glossary.py --vault . build --check    # exit 1 if the page would change (lint)
    python3 glossary.py --vault . link             # dry run: count first mentions that would be linked
    python3 glossary.py --vault . link --apply     # link them

The glossary page is hand-written down to and including its "## Registers" table; everything
after the first "## " heading that follows that table is regenerated by `build`:

    ## Registers

    | Section | Lead-in | Owner | ID pattern | Entry |
    |---|---|---|---|---|
    | Stakeholders | Roles and groups, by role only. | [[Stakeholder Register]] | STK-\\d{3} | {1}. Type: {2:lower}. |
    | Open questions | Each question with its status. | [[Open questions register]] | OQ-\\d{3} | {1} Status: {-1:status}. |

One row per register. `Owner` is the page that holds the register table (a wikilink; text after
it, such as "§ 13", is kept in the section lead). `ID pattern` is a regex the first token of a
table row's first cell must match in full. `Entry` is a template: `{id}` the ID, `{0}` the rest
of the first cell, `{1}`, `{2}`, `{-1}` the other cells; `{n:status}` keeps the leading status
word of a cell ("Partial" from "**Partial** - API …"), `{n:lower}` lowercases it.

`build` also writes one lookup table per family of pages that carry their ID in the filename
(`FR-001.md`, `FEAT-003 Title.md`, `BUG-012 Short title.md`): those link to their own pages, not
to the glossary. If `meta/adlc-upstream.md` exists, a "Plugin issues" section lists its UP-nnn
entries. The page's `updated:` is set to today when the content changes.

`link` turns the first mention of each known ID on a page into `[[glossary#ID|ID]]`, or into
`[[Page stem|ID]]` for an own-page ID (`\\|` inside a table cell). It leaves alone: frontmatter,
headings, code, existing links, URLs, `log.md`, log archives, lint reports, `glossary.md`,
`sources/`, `meta/operator-profile.md`, `meta/adlc-upstream.md` (verbatim records), the folders
listed under `link_skip:` in the glossary frontmatter (client documents, usually), the ID cell of
a register's own row, and a page's own ID. Standard library only. Exit 0 on success, 1 when
`--check` finds drift, 2 on bad input.
"""
import argparse
import collections
import datetime
import pathlib
import re
import sys

OWN_PAGE_ID = re.compile(r"^([A-Z]{1,5}-\d{2,4})(?:\s+(.*))?$")
SKIP_FILES = {"log.md", "glossary.md"}
SKIP_GLOBS = ("log-archive*.md", "lint-report-*.md")
SKIP_PATHS = ("sources/", "meta/operator-profile.md", "meta/adlc-upstream.md")


def fail(msg):
    print(f"glossary: {msg}", file=sys.stderr)
    sys.exit(2)


def split_cells(line):
    return [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]


def clean(text):
    """Strip bold, code and wikilink syntax, keeping the display text."""
    text = re.sub(r"\*\*|`", "", text)
    text = re.sub(r"\[\[([^\]|]+)\\?\|([^\]]+)\]\]", r"\2", text)
    text = re.sub(r"\[\[([^\]]+)\]\]", r"\1", text)
    return text.strip()


def status_word(text):
    """The leading status word(s) of a status cell, e.g. "Partial" from "**Partial** - API …"."""
    return re.split(r"\s+[—–-]\s+|;|\.|,", clean(text))[0].strip()


def frontmatter_list(text, key):
    m = re.search(rf"^{key}:\s*\[([^\]]*)\]\s*$", text, re.M)
    if m:
        return [v.strip().strip("\"'") for v in m.group(1).split(",") if v.strip()]
    m = re.search(rf"^{key}:\s*\n((?:\s+-\s+.*\n?)+)", text, re.M)
    if m:
        return [re.sub(r"^\s+-\s+", "", l).strip().strip("\"'") for l in m.group(1).splitlines()]
    return []


class Vault:
    def __init__(self, root):
        self.root = pathlib.Path(root).resolve()
        self.wiki = self.root / "wiki"
        if not self.wiki.is_dir():
            fail(f"no wiki/ under {self.root}")
        self.glossary = self.wiki / "glossary.md"
        if not self.glossary.is_file():
            fail(f"{self.glossary.relative_to(self.root)} not found; create it from the wiki skill's references/glossary.md")
        self._pages = None

    def pages(self):
        if self._pages is None:
            self._pages = sorted(p for p in self.wiki.rglob("*.md"))
        return self._pages

    def find_page(self, name):
        """Resolve a wikilink target by basename, as Obsidian does."""
        name = name.rsplit("/", 1)[-1]
        name = name[:-3] if name.lower().endswith(".md") else name
        hits = [p for p in self.pages() if p.stem.lower() == name.lower()]
        if not hits:
            fail(f"register page [[{name}]] not found under wiki/")
        return hits[0]

    def own_page_ids(self):
        """{ID: page stem} for pages whose filename starts with an ID."""
        out = {}
        for p in self.pages():
            if p.name.startswith("_"):
                continue
            m = OWN_PAGE_ID.match(p.stem)
            if m:
                out.setdefault(m.group(1), p.stem)
        return out


# ---------------------------------------------------------------- build

def parse_registers(text):
    """Rows of the ## Registers table and the offset where the generated part starts."""
    m = re.search(r"^## Registers\s*$", text, re.M)
    if not m:
        fail("glossary.md has no '## Registers' section (see the wiki skill's references/glossary.md)")
    rest = text[m.end():]
    nxt = re.search(r"^## ", rest, re.M)
    head_end = m.end() + (nxt.start() if nxt else len(rest))
    rows = []
    for line in rest[: nxt.start() if nxt else len(rest)].splitlines():
        if not line.startswith("|"):
            continue
        cells = split_cells(line)
        if len(cells) < 5 or cells[0] in ("Section", "") or set(cells[0]) <= {"-", ":"}:
            continue
        rows.append({"section": cells[0], "lead": cells[1], "owner": cells[2],
                     "pattern": cells[3].replace("\\|", "|"), "entry": cells[4]})
    return rows, head_end


def register_rows(page, pattern):
    """(id, rest_of_first_cell, cells) for table rows whose first token matches `pattern`."""
    out, seen = [], set()
    rx = re.compile(pattern)
    for line in page.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = split_cells(line)
        first = clean(cells[0])
        token = first.split()[0] if first else ""
        if token and rx.fullmatch(token) and token not in seen:
            seen.add(token)
            out.append((token, first[len(token):].strip(), cells))
    return out


FIELD = re.compile(r"\{(id|-?\d+)(?::(status|lower))?\}")


def render(template, ident, rest, cells):
    def sub(m):
        key, mod = m.group(1), m.group(2)
        if key == "id":
            val = ident
        elif key == "0":
            val = rest
        else:
            idx = int(key)
            try:
                val = cells[idx] if idx < 0 else cells[idx]
            except IndexError:
                val = ""
            val = clean(val)
        if mod == "status":
            val = status_word(val)
        elif mod == "lower":
            val = val.lower()
        return val
    return re.sub(r"\s+", " ", FIELD.sub(sub, template)).strip()


def build(vault, check):
    current = vault.glossary.read_text(encoding="utf-8")
    registers, head_end = parse_registers(current)
    head = current[:head_end].rstrip() + "\n"
    lines, counts = [head], collections.OrderedDict()

    for reg in registers:
        link = re.search(r"\[\[([^\]|#]+)", reg["owner"])
        if not link:
            fail(f"Registers row '{reg['section']}' has no [[Owner]] wikilink")
        page = vault.find_page(link.group(1))
        rows = register_rows(page, reg["pattern"])
        counts[reg["section"]] = len(rows)
        lines.append(f"## {reg['section']}\n\n{reg['lead']} Owned by {reg['owner']}.\n")
        for ident, rest, cells in rows:
            lines.append(f"### {ident}\n\n{render(reg['entry'], ident, rest, cells)}\n")

    upstream = vault.wiki / "meta" / "adlc-upstream.md"
    if upstream.is_file():
        up_text = upstream.read_text(encoding="utf-8")
        ups = re.findall(r"^### (UP-\d{3}) (.+)$", up_text, re.M)
        if ups:
            counts["Plugin issues"] = len(ups)
            lines.append("## Plugin issues\n\nIssues found in the adlc plugin while working in this vault. "
                         "Owned by [[adlc-upstream|ADLC upstream log]].\n")
            for ident, title in ups:
                entry = up_text.split(f"### {ident}", 1)[1].split("\n### ", 1)[0].split("\n## ", 1)[0]
                state = re.search(r"\*\*Status:\*\*\s*(.+)", entry)
                sent = re.search(r"\*\*Sent:\*\*\s*(.+)", entry)
                extra = "".join(f" {label}: {clean(m.group(1)).rstrip('.')}." for label, m
                                in (("Status", state), ("Sent", sent)) if m)
                lines.append(f"### {ident}\n\n{title.strip().rstrip('.')}.{extra}\n")

    own = vault.own_page_ids()
    if own:
        families = collections.OrderedDict()
        for ident, stem in own.items():
            families.setdefault(ident.rsplit("-", 1)[0], []).append((ident, stem))
        lines.append("## Pages with their own IDs\n\nThese have their own pages; link them directly, not here. "
                     "The tables list them for lookup.\n")
        for prefix, items in families.items():
            lines.append(f"| {prefix} | Title |\n|---|---|")
            for ident, stem in sorted(items):
                page = next(p for p in vault.pages() if p.stem == stem)
                h1 = [l for l in page.read_text(encoding="utf-8").splitlines() if l.startswith("# ")]
                title = (h1[0][2:] if h1 else stem).replace(ident, "", 1).strip(" :-")
                target = f"[[{stem}]]" if stem == ident else f"[[{stem}\\|{ident}]]"
                lines.append(f"| {target} | {title} |")
            lines.append("")

    new = "\n".join(lines).rstrip() + "\n"
    if new != current:
        today = datetime.date.today().isoformat()
        new = re.sub(r"^updated:.*$", f"updated: {today}", new, count=1, flags=re.M)
    changed = new != current
    total = len(re.findall(r"^### ", new, re.M))
    summary = ", ".join(f"{k} {v}" for k, v in counts.items())
    if check:
        print(f"glossary: {total} ID entries ({summary}); {'DRIFT: build would change the page' if changed else 'in step'}")
        sys.exit(1 if changed else 0)
    if changed:
        vault.glossary.write_text(new, encoding="utf-8")
    print(f"glossary: {total} ID entries ({summary}); {'updated' if changed else 'unchanged'}")


# ---------------------------------------------------------------- link

PROTECT = re.compile(r"`[^`]*`|\[\[[^\]]*\]\]|\[[^\]]*\]\([^)]*\)|<[^>]+>|https?://\S+")


def link(vault, apply):
    text = vault.glossary.read_text(encoding="utf-8")
    registers, _ = parse_registers(text)
    own = vault.own_page_ids()
    glossary_ids = [i for i in re.findall(r"^### (\S+)", text, re.M) if i not in own]
    ids = sorted(set(glossary_ids) | set(own), key=len, reverse=True)
    if not ids:
        fail("no IDs to link: run `build` first")
    pat = re.compile(r"(?<![A-Za-z0-9\-\[#/_])(" + "|".join(map(re.escape, ids)) + r")(?![A-Za-z0-9\-_])")
    already = re.compile(r"\[\[(?:glossary#)?(" + "|".join(map(re.escape, ids)) + r")(?![A-Za-z0-9\-_])")
    defining = set()
    for reg in registers:
        m = re.search(r"\[\[([^\]|#]+)", reg["owner"])
        if m:
            defining.add(vault.find_page(m.group(1)))
    skip_dirs = tuple(SKIP_PATHS) + tuple(d.rstrip("/") + "/" for d in frontmatter_list(text, "link_skip"))
    counts, changed_files = collections.Counter(), []

    for path in vault.pages():
        rel = path.relative_to(vault.wiki).as_posix()
        if path.name in SKIP_FILES or rel.startswith(skip_dirs) or rel in SKIP_PATHS \
                or any(path.match(g) for g in SKIP_GLOBS):
            continue
        src = path.read_text(encoding="utf-8")
        seen = set(already.findall(src))
        own_match = OWN_PAGE_ID.match(path.stem)
        if own_match:
            seen.add(own_match.group(1))
        out, in_frontmatter, in_code = [], False, False
        for n, line in enumerate(src.split("\n")):
            if n == 0 and line.strip() == "---":
                in_frontmatter = True
                out.append(line)
                continue
            if in_frontmatter:
                in_frontmatter = line.strip() != "---"
                out.append(line)
                continue
            if line.lstrip().startswith(("```", "~~~")):
                in_code = not in_code
                out.append(line)
                continue
            if in_code or line.lstrip().startswith("#"):
                out.append(line)
                continue
            is_table = line.lstrip().startswith("|")
            first_cell = None
            if is_table and path in defining:
                cells = split_cells(line)
                first = clean(cells[0]) if cells else ""
                first_cell = first.split()[0] if first else None
            bar = "\\|" if is_table else "|"

            def replace(m, first_cell=first_cell, bar=bar, seen=seen):
                ident = m.group(1)
                if ident == first_cell or ident in seen:
                    return ident
                if ident in own:
                    stem = own[ident]
                    target = f"[[{ident}]]" if stem == ident else f"[[{stem}{bar}{ident}]]"
                else:
                    target = f"[[glossary#{ident}{bar}{ident}]]"
                seen.add(ident)
                counts[ident.rsplit("-", 1)[0] if "-" in ident else re.sub(r"\d.*", "", ident)] += 1
                return target

            parts, last = [], 0
            for m in PROTECT.finditer(line):
                parts.append(pat.sub(replace, line[last:m.start()]))
                parts.append(m.group(0))
                last = m.end()
            parts.append(pat.sub(replace, line[last:]))
            out.append("".join(parts))
        new = "\n".join(out)
        if new != src:
            changed_files.append(rel)
            if apply:
                path.write_text(new, encoding="utf-8")

    mode = "linked" if apply else "would link"
    print(f"{mode}: {sum(counts.values())} first mentions in {len(changed_files)} pages {dict(counts)}")
    for rel in changed_files[:20]:
        print("  ", rel)
    if len(changed_files) > 20:
        print(f"   … and {len(changed_files) - 20} more")


def main():
    parser = argparse.ArgumentParser(description="Maintain wiki/glossary.md and the links to it.")
    parser.add_argument("--vault", default=".", help="vault root (the directory holding wiki/)")
    sub = parser.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="regenerate the ID entries from the registers")
    b.add_argument("--check", action="store_true", help="exit 1 if the page would change; write nothing")
    lk = sub.add_parser("link", help="link the first mention of each ID per page")
    lk.add_argument("--apply", action="store_true", help="write the changes (default: dry run)")
    args = parser.parse_args()
    vault = Vault(args.vault)
    if args.cmd == "build":
        build(vault, args.check)
    else:
        link(vault, args.apply)


if __name__ == "__main__":
    main()
